// Supplemental 6×7 bitmaps for the Linux development console.
pub(super) fn glyph(byte: u8) -> Option<[u8; 7]> {
    Some(match byte {
        b'5' => [0x3e, 0x20, 0x20, 0x3c, 0x02, 0x22, 0x1c],
        b'6' => [0x0c, 0x10, 0x20, 0x3c, 0x22, 0x22, 0x1c],
        b'7' => [0x3e, 0x02, 0x04, 0x08, 0x10, 0x10, 0x10],
        b'8' => [0x1c, 0x22, 0x22, 0x1c, 0x22, 0x22, 0x1c],
        b'9' => [0x1c, 0x22, 0x22, 0x1e, 0x02, 0x04, 0x18],
        b'j' => [0x04, 0x00, 0x0c, 0x04, 0x04, 0x24, 0x18],
        b'q' => [0x00, 0x1a, 0x26, 0x22, 0x1e, 0x02, 0x02],
        b'v' => [0x00, 0x22, 0x22, 0x22, 0x22, 0x14, 0x08],
        b'(' => [0x04, 0x08, 0x10, 0x10, 0x10, 0x08, 0x04],
        b')' => [0x10, 0x08, 0x04, 0x04, 0x04, 0x08, 0x10],
        b',' => [0x00, 0x00, 0x00, 0x00, 0x00, 0x08, 0x10],
        b'/' => [0x02, 0x02, 0x04, 0x08, 0x10, 0x20, 0x20],
        b'<' => [0x00, 0x04, 0x08, 0x10, 0x08, 0x04, 0x00],
        b'>' => [0x00, 0x10, 0x08, 0x04, 0x08, 0x10, 0x00],
        b'?' => [0x1c, 0x22, 0x02, 0x04, 0x08, 0x00, 0x08],
        b'[' => [0x1c, 0x10, 0x10, 0x10, 0x10, 0x10, 0x1c],
        b']' => [0x1c, 0x04, 0x04, 0x04, 0x04, 0x04, 0x1c],
        _ => return None,
    })
}

#[cfg(test)]
mod tests {
    #[test]
    fn calendar_glyphs_are_distinct_printable_bitmaps() {
        let mut rows = std::collections::BTreeSet::new();
        for &byte in b"56789jqv(),/<>?[]" {
            let bitmap = super::glyph(byte).unwrap();
            assert!(bitmap.iter().any(|row| *row != 0));
            assert!(bitmap.iter().all(|row| *row < 64));
            assert!(rows.insert(bitmap));
        }
        assert_eq!(super::glyph(b'0'), None);
        assert_eq!(super::glyph(b' '), None);
    }
}
